"""Schema for evaluation_report.json artifact."""

from datetime import datetime
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field, field_validator

from .base import VersionedArtifact


class ClassificationMetrics(BaseModel):
    """Classification performance metrics."""
    
    accuracy: float = Field(ge=0.0, le=1.0, description="Classification accuracy")
    precision: float = Field(ge=0.0, le=1.0, description="Precision score (weighted)")
    recall: float = Field(ge=0.0, le=1.0, description="Recall score (weighted)")
    f1_score: float = Field(ge=0.0, le=1.0, description="F1 score (weighted)")
    roc_auc: Optional[float] = Field(default=None, ge=0.0, le=1.0, description="ROC AUC for binary classification")
    
    model_config = {"extra": "forbid"}


class RegressionMetrics(BaseModel):
    """Regression performance metrics."""
    
    r2_score: float = Field(description="R-squared score")
    mean_squared_error: float = Field(ge=0.0, description="Mean squared error")
    root_mean_squared_error: float = Field(ge=0.0, description="Root mean squared error")
    mean_absolute_error: float = Field(ge=0.0, description="Mean absolute error")
    mean_absolute_percentage_error: Optional[float] = Field(default=None, description="MAPE as percentage")
    
    model_config = {"extra": "forbid"}


class EvaluationReportSchema(VersionedArtifact):
    """Schema for evaluation_report.json generated by evaluate command.
    
    Contains model evaluation results and performance metrics.
    """
    
    task_type: str = Field(description="classification or regression")
    sample_size: int = Field(ge=0, description="Number of samples evaluated")
    predictions_made: int = Field(ge=0, description="Number of predictions made")
    
    metrics: Dict[str, Any] = Field(description="Performance metrics (varies by task type)")
    
    confusion_matrix: Optional[List[List[int]]] = Field(
        default=None,
        description="Confusion matrix (classification only)"
    )
    
    classification_report: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Per-class classification report"
    )
    
    model_name: Optional[str] = Field(default=None, description="Name of evaluated model")
    model_path: Optional[str] = Field(default=None, description="Path to model file")
    
    evaluation_timestamp: Optional[datetime] = Field(
        default=None,
        description="When evaluation was performed"
    )
    
    @field_validator('task_type')
    @classmethod
    def validate_task_type(cls, v):
        if v not in ['classification', 'regression']:
            raise ValueError('task_type must be "classification" or "regression"')
        return v
    
    @property
    def is_classification(self) -> bool:
        """Check if this is a classification task."""
        return self.task_type == "classification"
    
    @property
    def is_regression(self) -> bool:
        """Check if this is a regression task."""
        return self.task_type == "regression"
    
    @property
    def primary_metric(self) -> float:
        """Get the primary evaluation metric."""
        if self.is_classification:
            return self.metrics.get("accuracy", 0.0)
        return self.metrics.get("r2_score", 0.0)
    
    @property
    def performance_level(self) -> str:
        """Get human-readable performance level."""
        primary = self.primary_metric
        if self.is_classification:
            if primary >= 0.9:
                return "excellent"
            elif primary >= 0.8:
                return "good"
            elif primary >= 0.7:
                return "fair"
            else:
                return "needs_improvement"
        else:
            if primary >= 0.9:
                return "excellent"
            elif primary >= 0.7:
                return "good"
            elif primary >= 0.5:
                return "fair"
            else:
                return "needs_improvement"
    
    @property
    def precision_recall_gap(self) -> float:
        """Gap between precision and recall (indicates class imbalance impact)."""
        if self.is_classification:
            precision = self.metrics.get("precision", 0.0)
            recall = self.metrics.get("recall", 0.0)
            return abs(precision - recall)
        return 0.0
    
    def get_classification_metrics(self) -> Optional[ClassificationMetrics]:
        """Get typed classification metrics if this is a classification task."""
        if not self.is_classification:
            return None
        try:
            return ClassificationMetrics(**self.metrics)
        except Exception:
            return None
    
    def get_regression_metrics(self) -> Optional[RegressionMetrics]:
        """Get typed regression metrics if this is a regression task."""
        if not self.is_regression:
            return None
        try:
            return RegressionMetrics(**self.metrics)
        except Exception:
            return None
    
    model_config = {
        "json_schema_extra": {
            "description": "Evaluation report schema for model performance artifacts",
            "examples": [{
                "schema_version": "1.0.0",
                "created_at": "2026-02-22T10:40:00",
                "task_type": "classification",
                "sample_size": 200,
                "predictions_made": 200,
                "metrics": {
                    "accuracy": 0.92,
                    "precision": 0.91,
                    "recall": 0.93,
                    "f1_score": 0.92,
                    "roc_auc": 0.96
                },
                "confusion_matrix": [[90, 5], [11, 94]]
            }]
        },
        "extra": "forbid",
    }
